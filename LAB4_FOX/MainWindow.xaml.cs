📖 СПРАВКА ПО ПРОГРАММЕ 'ЛОГИЧЕСКИЕ ФУНКЦИИ - ЛР4'

ОПИСАНИЕ ПРОГРАММЫ:
• Инструмент для работы с булевыми (логическими) функциями
• Задание функций по номеру или по формуле
• Построение таблиц истинности
• Генерация ДНФ и КНФ в базисе {НЕ, И, ИЛИ}
• Проверка эквивалентности функций

ОБОЗНАЧЕНИЯ ОПЕРАТОРОВ:
! или ¬    - оператор НЕ (отрицание)
& или ∧    - оператор И (конъюнкция)
| или ∨    - оператор ИЛИ (дизъюнкция)
^          - исключающее ИЛИ (XOR)
-> или →   - импликация (логическое следствие)
= или ↔    - эквивалентность

РАЗВЕРТЫВАНИЕ ОПЕРАТОРОВ В БАЗИС:
• A -> B  превращается в  !A | B
• A = B   превращается в  (A & B) | (!A & !B)
• A ^ B   превращается в  (A & !B) | (!A & B)

ВКЛАДКА 'ПО НОМЕРУ':
• n - количество переменных (от 1 до 8)
• num - номер функции от 0 до 2^(2^n)-1
• Номер в двоичном виде определяет таблицу истинности
• Пример: n=3, num=11 (00001011₂) соответствует:
  000→1, 001→1, 010→0, 011→1, 100→0, 101→0, 110→0, 111→0

ВКЛАДКА 'ПО ФОРМУЛЕ':
• Ввод логической формулы с автоматическим разбором
• Поддержка сложных выражений со скобками
• Все операторы разворачиваются в базис {НЕ, И, ИЛИ}

ВКЛАДКА 'СРАВНЕНИЕ':
• Проверка, являются ли две функции одинаковыми
• Если функции различаются - показывается контрпример
• Можно сравнивать функции заданные как по номеру, так и по формуле

DNF И KNF:
• DNF - объединение условий, когда функция равна 1
• KNF - пересечение условий, когда функция равна 0
• Стоимость формулы показывает сложность выражения

ПРЕДУПРЕЖДЕНИЕ:
• При количестве переменных n > 6 вычисления могут замедлиться
• Максимальное количество переменных: 8

ПРИМЕРЫ ДЛЯ ТЕСТИРОВАНИЯ:
1. n=3, num=11 → посмотреть таблицу и ДНФ/КНФ
2. (x1 | x2) -> x3 → разбор формулы и вычисление
3. x1 & !x2 | x3 → сравнение с ДНФ-формой

